import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { run } from "../lib/utils.mjs";
import { publishImplementationResult } from "../commands/graph/implementation-result.mjs";
import { getCheckoutGraphSnapshot } from "../commands/graph/actions.mjs";

test("Implement results appear in the main tree, follow amendments, and survive task ref cleanup", async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), "tb-result-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = async (...args) => String(await run({ cmd: "git", args, cwd: root, capture: true, silent: true })).trim();
  await git("init", "-b", "main");
  await git("config", "user.name", "Test");
  await git("config", "user.email", "test@example.invalid");
  await git("config", "commit.gpgsign", "false");
  await writeFile(path.join(root, "calendar.txt"), "base\n");
  await git("add", "."); await git("commit", "-m", "Base");
  await git("branch", "Bug-123");
  const branch = "tb-task/task-id/Bug-123";
  await git("switch", "-c", branch);
  await writeFile(path.join(root, "calendar.txt"), "implementation\n");
  await git("commit", "-am", "Implement Calendar");
  const state = { path: root, repositoryPath: root, branch, bugId: 123, commitHash: await git("rev-parse", "HEAD") };
  const options = { runCommand: run, save() {} };
  await publishImplementationResult(state, options);
  assert.equal(state.branch, "Bug-123_2");
  assert.equal(await git("branch", "--show-current"), state.branch);
  assert.equal(await git("for-each-ref", "--format=%(refname)", `refs/heads/${branch}`), "");
  await git("switch", "main");
  const graph = { path: root, repository: "comm", checkout: "working" };
  const snapshot = await getCheckoutGraphSnapshot({ graph, runCommand: run });
  assert.ok(snapshot.commits.some(commit => commit.hash === state.commitHash && commit.refs.includes(state.branch)));
  await git("switch", state.branch);
  await writeFile(path.join(root, "calendar.txt"), "amended implementation\n");
  await git("commit", "-am", "Implement Calendar", "--amend");
  state.commitHash = await git("rev-parse", "HEAD");
  await publishImplementationResult(state, options);
  assert.equal(await git("rev-parse", state.branch), state.commitHash);
  await git("switch", "main");
  await git("update-ref", "refs/heads/tb-task/old/result", state.commitHash);
  await git("branch", "-D", "tb-task/old/result");
  assert.equal(await git("show", `${state.branch}:calendar.txt`), "amended implementation");
});
